def interpretation_hints(num_objects: int, mean_conf: float) -> str:
    """根据统计量生成一段通用解读线索（作为报告中 LLM 解读的兜底）。"""
    if num_objects == 0:
        return ("本次未检出舰船。可能原因：图像内确无目标、置信度阈值偏高，"
                "或目标尺寸过小低于检测器下限；可尝试降低置信度阈值后重新检测。")
    scene = ("目标较密集，排列若规则可能为港口/码头，间距均匀则可能为锚地"
             if num_objects >= 10 else "目标数量较少，更可能为开阔海面上的孤立船只或小型船队")
    conf_level = ("平均置信度较高，整体结果可信"
                  if mean_conf >= 0.6 else
                  "平均置信度偏低，存在一定虚警与漏检可能，建议结合原图人工复核低分框")
    return (f"本次共检出 {num_objects} 个舰船目标，{scene}；{conf_level}。"
            "注意：SAR 图像中舰船表现为亮斑，暗斑多为阴影区；"
            "低置信度框需警惕虚警（参见术语：虚警）。")
